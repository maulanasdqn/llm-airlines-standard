use crate::spec::dictionary::{Dictionary, WordEntry};
use crate::spec::rules::Rule;

const GENERATED_NOTE: &str = "<!-- Generated by ste build. Edit the source in spec/, then run the build. -->";
const WORDS_PER_ITEM: usize = 8;

pub fn render_json(value: &impl serde::Serialize) -> String {
    serde_json::to_string_pretty(value).unwrap_or_default() + "\n"
}

fn render_rows(headers: &[&str], rows: &[Vec<String>]) -> Vec<String> {
    let mut lines = vec![format!("| {} |", headers.join(" | ")), format!("|{}", "---|".repeat(headers.len()))];
    lines.extend(rows.iter().map(|row| format!("| {} |", row.join(" | "))));
    lines.push(String::new());
    lines
}

fn render_word_list(words: &[String]) -> Vec<String> {
    let mut lines: Vec<String> = words.chunks(WORDS_PER_ITEM).map(|group| format!("- {}", group.join(", "))).collect();
    lines.push(String::new());
    lines
}

fn render_avoid_rows(entries: &[WordEntry]) -> Vec<String> {
    render_rows(
        &["Do not use", "Use"],
        &entries.iter().map(|entry| vec![format!("`{}`", entry.word), entry.replacement.clone()]).collect::<Vec<_>>(),
    )
}

fn render_verbs(dictionary: &Dictionary) -> Vec<String> {
    let mut lines = vec![
        "## Approved verbs".into(),
        String::new(),
        "Each verb has one contract. Use it only for that contract.".into(),
        String::new(),
    ];
    let verbs: Vec<Vec<String>> = dictionary
        .verbs
        .iter()
        .map(|entry| vec![format!("`{}`", entry.word), entry.meaning.clone(), entry.not_for.clone()])
        .collect();
    lines.extend(render_rows(&["Verb", "Meaning", "Do not use it for"], &verbs));
    lines.extend(["## Predicates and prefixes".into(), String::new()]);
    let mut rows: Vec<Vec<String>> =
        dictionary.predicates.iter().map(|entry| vec![format!("`{}`", entry.word), entry.meaning.clone()]).collect();
    rows.extend(
        dictionary
            .prefixes
            .iter()
            .map(|entry| vec![format!("`{}`", entry.word), format!("{} Example: `{}`.", entry.meaning, entry.example)]),
    );
    lines.extend(render_rows(&["Word", "Meaning"], &rows));
    lines
}

pub fn render_dictionary(dictionary: &Dictionary) -> String {
    let mut lines = vec![GENERATED_NOTE.into(), String::new(), "# STE-C dictionary".into(), String::new()];
    lines.extend(["The code rules use these words. A project adds its own words in LEXICON.md.".into(), String::new()]);
    lines.extend(render_verbs(dictionary));
    lines.extend(["## Verbs to avoid".into(), String::new()]);
    lines.extend(render_avoid_rows(&dictionary.avoid_verbs));
    lines.extend(["## Words to avoid in names".into(), String::new()]);
    lines.extend(render_avoid_rows(&dictionary.avoid_nouns));
    lines.extend(["## Abbreviations".into(), String::new(), "These abbreviations are approved:".into(), String::new()]);
    lines.extend(render_word_list(
        &dictionary.abbreviations.approved.iter().map(|word| format!("`{word}`")).collect::<Vec<_>>(),
    ));
    lines.extend(["Do not use these abbreviations:".into(), String::new()]);
    lines.extend(render_avoid_rows(&dictionary.abbreviations.avoid));
    lines.extend([
        "## Synonym groups".into(),
        String::new(),
        "In one codebase, use one verb from a group for one object (C1.3).".into(),
        String::new(),
    ]);
    lines.extend(
        dictionary
            .synonym_groups
            .iter()
            .map(|group| format!("- {}", group.iter().map(|word| format!("`{word}`")).collect::<Vec<_>>().join(", "))),
    );
    lines.join("\n") + "\n"
}

pub fn render_words(dictionary: &Dictionary) -> String {
    let prose = &dictionary.prose;
    let mut lines = vec![GENERATED_NOTE.into(), String::new(), "# Words to avoid in prose".into(), String::new()];
    lines.extend(["This list is our own. It is not the ASD-STE100 dictionary.".into(), String::new()]);
    let rows: Vec<Vec<String>> = prose
        .avoid
        .iter()
        .map(|entry| vec![format!("\"{}\"", entry.text), entry.replacement.clone(), entry.rule.clone()])
        .collect();
    lines.extend(render_rows(&["Do not use", "Use", "Rule"], &rows));
    lines.extend([
        "## Hedges".into(),
        String::new(),
        "Use 1 or fewer of these words in each sentence (W4.3):".into(),
        String::new(),
    ]);
    lines.extend(render_word_list(&prose.hedges.iter().map(|word| format!("\"{word}\"")).collect::<Vec<_>>()));
    lines.join("\n")
}

fn render_sections(rules: &[Rule]) -> Vec<String> {
    let mut rows = Vec::new();
    for section in 1..=9 {
        let writing: Vec<&Rule> =
            rules.iter().filter(|rule| rule.section == section && rule.id.starts_with('W')).collect();
        let code: Vec<&Rule> =
            rules.iter().filter(|rule| rule.section == section && rule.id.starts_with('C')).collect();
        let (Some(first_writing), Some(first_code)) = (writing.first(), code.first()) else {
            continue;
        };
        rows.push(vec![
            section.to_string(),
            first_writing.section_title.clone(),
            first_code.section_title.clone(),
            writing.len().to_string(),
            code.len().to_string(),
        ]);
    }
    render_rows(&["Section", "Writing (W)", "Code (C)", "W rules", "C rules"], &rows)
}

pub fn render_mapping(rules: &[Rule]) -> String {
    let mut lines = vec![GENERATED_NOTE.into(), String::new(), "# Map of the rules".into(), String::new()];
    lines.extend(["Section N of the writing rules maps to section N of the code rules.".into(), String::new()]);
    lines.extend(render_sections(rules));
    lines.extend([
        "## Rules and checks".into(),
        String::new(),
        "The value \"review\" means that a person or an agent checks the rule.".into(),
        String::new(),
    ]);
    let rows: Vec<Vec<String>> = rules
        .iter()
        .map(|rule| {
            let checks = rule.checks.iter().map(|check| format!("`{check}`")).collect::<Vec<_>>().join(", ");
            vec![rule.id.clone(), rule.title.clone(), rule.severity.clone(), checks]
        })
        .collect();
    lines.extend(render_rows(&["Rule", "Title", "Severity", "Checks"], &rows));
    lines.join("\n")
}
