from __future__ import annotations

import json

GENERATED_NOTE = "<!-- Generated by tools/build.py. Edit the source in spec/, then run the build. -->"


WORDS_PER_ITEM = 8


def render_word_list(words: list) -> list:
    groups = [words[start : start + WORDS_PER_ITEM] for start in range(0, len(words), WORDS_PER_ITEM)]
    return [f"- {', '.join(group)}" for group in groups] + [""]


def render_json(value: object) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def render_rows(headers: list, rows: list) -> list:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines.extend("| " + " | ".join(str(cell) for cell in row) + " |" for row in rows)
    return lines + [""]


def render_verbs(dictionary: dict) -> list:
    lines = ["## Approved verbs", "", "Each verb has one contract. Use it only for that contract.", ""]
    rows = [(f"`{entry['word']}`", entry["meaning"], entry["not_for"]) for entry in dictionary["verbs"]]
    lines += render_rows(["Verb", "Meaning", "Do not use it for"], rows)
    lines += ["## Predicates and prefixes", ""]
    rows = [(f"`{entry['word']}`", entry["meaning"]) for entry in dictionary["predicates"]]
    rows += [(f"`{entry['word']}`", entry["meaning"] + f" Example: `{entry['example']}`.") for entry in dictionary["prefixes"]]
    return lines + render_rows(["Word", "Meaning"], rows)


def render_avoided(dictionary: dict) -> list:
    lines = ["## Verbs to avoid", ""]
    lines += render_rows(["Do not use", "Use"], [(f"`{entry['word']}`", entry["use"]) for entry in dictionary["avoid_verbs"]])
    lines += ["## Words to avoid in names", ""]
    lines += render_rows(["Do not use", "Use"], [(f"`{entry['word']}`", entry["use"]) for entry in dictionary["avoid_nouns"]])
    abbreviations = dictionary["abbreviations"]
    lines += ["## Abbreviations", "", "These abbreviations are approved:", ""]
    lines += render_word_list([f"`{word}`" for word in abbreviations["approved"]])
    lines += ["Do not use these abbreviations:", ""]
    return lines + render_rows(["Do not use", "Use"], [(f"`{entry['word']}`", entry["use"]) for entry in abbreviations["avoid"]])


def render_dictionary(dictionary: dict) -> str:
    lines = [GENERATED_NOTE, "", "# STE-C dictionary", ""]
    lines += ["The code rules use these words. A project adds its own words in LEXICON.md.", ""]
    lines += render_verbs(dictionary) + render_avoided(dictionary)
    lines += ["## Synonym groups", "", "In one codebase, use one verb from a group for one object (C1.3).", ""]
    lines += [f"- {', '.join(f'`{word}`' for word in group)}" for group in dictionary["synonym_groups"]]
    return "\n".join(lines) + "\n"


def render_words(dictionary: dict) -> str:
    prose = dictionary["prose"]
    lines = [GENERATED_NOTE, "", "# Words to avoid in prose", ""]
    lines += ["This list is our own. It is not the ASD-STE100 dictionary.", ""]
    rows = [(f'"{entry["text"]}"', entry["use"], entry["rule"]) for entry in prose["avoid"]]
    lines += render_rows(["Do not use", "Use", "Rule"], rows)
    lines += ["## Hedges", "", "Use 1 or fewer of these words in each sentence (W4.3):", ""]
    lines += render_word_list([f'"{word}"' for word in prose["hedges"]])
    return "\n".join(lines)


def render_section_rows(sections: dict) -> list:
    rows = []
    for number in sorted(sections):
        writing, code = sections[number]["W"], sections[number]["C"]
        rows.append((number, writing[0]["section_title"], code[0]["section_title"], len(writing), len(code)))
    return render_rows(["Section", "Writing (W)", "Code (C)", "W rules", "C rules"], rows)


def render_mapping(rules: list) -> str:
    sections = {}
    for rule in rules:
        sections.setdefault(rule["section"], {"W": [], "C": []})[rule["id"][0]].append(rule)
    lines = [GENERATED_NOTE, "", "# Map of the rules", ""]
    lines += ["Section N of the writing rules maps to section N of the code rules.", ""]
    lines += render_section_rows(sections)
    lines += ["## Rules and checks", "", "The value \"review\" means that a person or an agent checks the rule.", ""]
    rows = [(rule["id"], rule["title"], rule["severity"], ", ".join(f"`{check}`" for check in rule["checks"])) for rule in rules]
    return "\n".join(lines + render_rows(["Rule", "Title", "Severity", "Checks"], rows))


def build_checker_bundle(rules: list, limits: dict, dictionary: dict) -> dict:
    return {
        "rules": {rule["id"]: {"title": rule["title"], "severity": rule["severity"]} for rule in rules},
        "limits": limits,
        "dictionary": dictionary,
    }
